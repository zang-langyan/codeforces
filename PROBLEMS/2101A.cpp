void solve() {
    int n;
    cin >> n;
    vector<vector<int>> m(n, vi(n, -1));
    int i = (n-1) / 2, j = (n-1) / 2;
    m[i][j] = 0;
    vector<vi> dir {
        {0, 1},
        {1, 0},
        {0, -1},
        {-1, 0},
    };
    int s = 1, c = 1;
    while (c < n * n) {
        for (int d = 0; d < 4; ++d) {
            int steps = s;
            s += d % 2;
            int dx = dir[d][0], dy = dir[d][1];
            while (steps--) {
                i += dx;
                j += dy;
                if (i < 0 || i >= n || j < 0 || j >= n || m[i][j] != -1) continue;
                m[i][j] = c++;
                if (c >= n * n) break;
            }
            if (c >= n * n) break;
        }
    }
    for (auto& r : m) {
        cout << r << endl;
    }
}
