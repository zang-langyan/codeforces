template<class T>
std::ostream& operator<<(std::ostream& os, const std::vector<T>& v) {
    for (int i = 0; i < v.size(); ++i) {
        os << (i > 0 ? " " : "") << v[i];
    }
    return os;
}

template<class T>
vector<T> operator+(const vector<T>& a, const vector<T>& b) {
    if (a.size() != b.size()) return {};
    vector<T> res(a.size());
    for (int i = 0; i < a.size(); ++i) {
        res[i] = a[i] + b[i];
    }
    return res;
}

void solve() {
    int n;
    cin >> n;
    cout << 2 * n - 1 << endl;
    for (int i = 1; i <= n; ++i) {
        cout << i << " " << 1 << " " << i << endl;
        if (i+1 <= n)
        cout << i << " " << i+1 << " " << n << endl;
    }
}

