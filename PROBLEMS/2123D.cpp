template<class T>
std::ostream& operator<<(std::ostream& os, const std::vector<T>& v) {
    for (int i = 0; i < v.size(); ++i) {
        os << (i > 0 ? " " : "") << v[i];
    }
    return os;
}

template<class T>
vector<T> operator+(const vector<T>& a, const vector<T>& b) {
    if (a.size() != b.size()) return {};
    vector<T> res(a.size());
    for (int i = 0; i < a.size(); ++i) {
        res[i] = a[i] + b[i];
    }
    return res;
}

void solve() {
    int n, k;
    cin >> n >> k;
    int one = 0;
    for (int i = 0; i < n; ++i) {
        char c;
        cin >> c;
        if (c == '1') {
            ++one;
        }
    }
    if (one <= k) {
        cout << "Alice\n";
        return;
    }
    if (k == 1) {
        cout << "Bob\n";
        return;
    }
    if (k < (n + 2) / 2) {
        cout << "Bob\n";
    } else {
        cout << "Alice\n";
    }
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(0);

    int t;
    cin >> t;
    while (t--) solve();
}

